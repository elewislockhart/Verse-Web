"""Build data/verses.js from the lds-scriptures SQLite export.

Usage:  python tools/build_data.py [path/to/lds-scriptures-sqlite.db]

Writes a plain script (not JSON) so index.html works when opened from file://,
where browsers block fetch().
"""
import json
import sqlite3
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = ROOT / "tools" / "source" / "lds-scriptures-sqlite.db"
OUT = ROOT / "data" / "verses.js"


def main() -> None:
    db_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DB
    if not db_path.exists():
        sys.exit(f"Database not found: {db_path}")

    con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    volumes = con.execute(
        "SELECT id, volume_title FROM volumes ORDER BY id"
    ).fetchall()
    # Volume index in the output is 0-based position in this list.
    vol_index = {vid: i for i, (vid, _) in enumerate(volumes)}

    rows = con.execute(
        "SELECT verse_title, verse_short_title, volume_id, scripture_text "
        "FROM scriptures ORDER BY volume_id, book_id, chapter_id, verse_id"
    ).fetchall()
    con.close()

    verses = [[t, s, vol_index[v], text] for t, s, v, text in rows]
    data = {"volumes": [title for _, title in volumes], "verses": verses}

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// Generated by tools/build_data.py - do not edit.\n"
        "// Source: github.com/beandog/lds-scriptures (2020.12.08), public domain.\n"
        f"window.VERSE_DATA={payload};\n",
        encoding="utf-8",
    )

    counts = Counter(v[2] for v in verses)
    print(f"Wrote {len(verses):,} verses to {OUT.relative_to(ROOT)} "
          f"({OUT.stat().st_size / 1e6:.1f} MB)")
    for i, title in enumerate(data["volumes"]):
        print(f"  {title}: {counts[i]:,}")


if __name__ == "__main__":
    main()
